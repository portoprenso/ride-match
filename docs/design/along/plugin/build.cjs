/** Bundle the reviewed design sources for Figma's standard, offline Plugin API. */
const fs = require('node:fs');
const path = require('node:path');
const here = __dirname;
const read = file => fs.readFileSync(path.join(here, file), 'utf8');

/** Fail on source drift instead of silently producing a partially adapted importer. */
function replaceOnce(source, before, after) {
  if (!source.includes(before)) throw new Error('Missing build anchor: ' + before);
  return source.replace(before, after);
}

let helpers = read('../source/helpers.js');
helpers = replaceOnce(helpers, 'figma.createAutoLayout(dir)', 'autoFrame(dir)');
helpers = replaceOnce(helpers, 'function track(n){made.push(n.id);return n;}', 'function track(n){made.push(n.id);run.nodeIds.add(n.id);return n;}');
helpers = replaceOnce(helpers, "handle.layoutAlign='CENTER'", "s.counterAxisAlignItems='CENTER'");
helpers += '\nfunction autoFrame(dir){const node=figma.createFrame();node.layoutMode=dir;return node;}\n';

function bundle(name) {
  let source = read('../source/' + name + '.js');
  if (name === 'kit') {
    source = replaceOnce(source, 'cover.placeholder=false;kit.placeholder=false;', '');
    source = replaceOnce(source, 'Start on page 01, screen 01. Primary buttons connect the demo journey.\\nPage 02 covers recovery, safety and settings.', 'Start at screen 01. Primary buttons connect the demo journey.\\nAll 55 screens share one canvas, including recovery, safety and settings.');
  } else {
    source = replaceOnce(source, name === 'journey'
      ? "if(page.children.length)throw new Error('Journey already exists; inspect before resuming');"
      : "if(page.children.length)throw new Error('States already exist; inspect first');", '');
    // Screens stay top-level so native prototype reactions can reach every state.
    source = replaceOnce(source, 'const f=await phone(page,key,names[i]);', 'if(onlyKeys&&!onlyKeys.has(key))continue;const f=await phone(page,key,names[i]);');
    if (name === 'states') {
      source = replaceOnce(source, "const key=String(51+i),f=await phone(page,key,extraNames[i]);", "const key=String(51+i);if(onlyKeys&&!onlyKeys.has(key))continue;const f=await phone(page,key,extraNames[i]);");
    }
    // The host connects all 55 screens together and preserves pre-existing flows.
    source = source.slice(0, source.indexOf(name === 'journey' ? 'const ownLinks=' : 'let linked=0;'));
    source += '\nreturn {screens, boards, links};';
  }
  return 'async function build' + name[0].toUpperCase() + name.slice(1) + '(S,run,onlyKeys){\n' + helpers + '\n' + source + '\n}\n';
}

const code = '// Generated by build.cjs. Edit runtime.js or the construction sources.\n'
  + ['kit', 'journey', 'states'].map(bundle).join('\n') + read('runtime.js');
if (/createAutoLayout|\.placeholder|layoutAlign='CENTER'/.test(code)) throw new Error('Unadapted MCP-only API');
new (require('node:vm').Script)(code);
fs.writeFileSync(path.join(here, 'code.js'), code);
console.log('Built offline Figma plugin (' + Buffer.byteLength(code) + ' bytes).');
